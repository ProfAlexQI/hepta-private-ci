fn lint_allowlist_audit() -> AuditResult<()> {
    let mut allow_findings = Vec::new();
    for root in ["apps", "crates"] {
        for file in walk_paths(Path::new(root), &[])? {
            if file.extension().and_then(|ext| ext.to_str()) != Some("rs") {
                continue;
            }
            let text = fs::read_to_string(&file).map_err(|err| err.to_string())?;
            for body in clippy_allow_bodies(&text) {
                let lint_count = body.matches("clippy::").count();
                if lint_count > 0 {
                    allow_findings.push(json!({
                        "file": file.to_string_lossy(),
                        "lint_count": lint_count,
                        "body": compact(&body).chars().take(240).collect::<String>(),
                    }));
                }
            }
        }
    }
    let total_lints = allow_findings
        .iter()
        .map(|item| item.get("lint_count").and_then(Value::as_u64).unwrap_or(0) as usize)
        .sum::<usize>();
    ensure(
        total_lints <= 32,
        format!("clippy allowlist budget exceeded: {total_lints}"),
    )?;
    ensure(
        Path::new("docs/quality/HEPTA_CLIPPY_ALLOWLIST_BURNDOWN_2026-04-28.md").exists(),
        "allowlist burn-down ledger missing".to_string(),
    )?;
    write_json(
        "target/hepta-lint-allowlist-audit/manifest.json",
        &json!({
            "smoke": "hepta-lint-allowlist-audit",
            "status": "complete",
            "allow_attribute_count": allow_findings.len(),
            "allowed_clippy_lint_count": total_lints,
            "budget": 32,
            "findings": allow_findings,
        }),
    )?;
    println!("Hepta lint allowlist audit passed");
    Ok(())
}

fn panic_surface_audit() -> AuditResult<()> {
    let mut files = Vec::new();
    for root in ["apps", "crates"] {
        for file in walk_paths(Path::new(root), &[])? {
            if file.extension().and_then(|ext| ext.to_str()) == Some("rs") {
                files.push(file);
            }
        }
    }
    let mut findings = Vec::new();
    let mut totals = BTreeMap::from([
        ("unwrap", 0usize),
        ("expect", 0usize),
        ("panic", 0usize),
        ("todo", 0usize),
        ("unimplemented", 0usize),
    ]);
    for file in &files {
        let text = fs::read_to_string(file).map_err(|err| err.to_string())?;
        let unwrap = text.matches(".unwrap()").count();
        let expect = text.matches(".expect(").count();
        let panic = count_macro_call(&text, "panic!");
        let todo = count_macro_call(&text, "todo!");
        let unimplemented = count_macro_call(&text, "unimplemented!");
        let test_markers = text.matches("#[test]").count() + text.matches("mod tests").count();
        if unwrap + expect + panic + todo + unimplemented > 0 {
            findings.push(json!({
                "file": file.to_string_lossy(),
                "unwrap": unwrap,
                "expect": expect,
                "panic": panic,
                "todo": todo,
                "unimplemented": unimplemented,
                "test_markers": test_markers,
            }));
        }
        *totals.get_mut("unwrap").expect("totals key") += unwrap;
        *totals.get_mut("expect").expect("totals key") += expect;
        *totals.get_mut("panic").expect("totals key") += panic;
        *totals.get_mut("todo").expect("totals key") += todo;
        *totals.get_mut("unimplemented").expect("totals key") += unimplemented;
    }
    ensure(
        totals.get("todo").copied().unwrap_or(0) == 0,
        "panic audit forbids todo! in source".to_string(),
    )?;
    ensure(
        totals.get("unimplemented").copied().unwrap_or(0) == 0,
        "panic audit forbids unimplemented! in source".to_string(),
    )?;
    ensure(
        Path::new("docs/quality/HEPTA_PANIC_SURFACE_AUDIT_2026-04-28.md").exists(),
        "panic surface audit requires quality ledger".to_string(),
    )?;
    findings.sort_by(|a, b| {
        let score = |item: &Value| {
            item.get("unwrap").and_then(Value::as_u64).unwrap_or(0)
                + item.get("expect").and_then(Value::as_u64).unwrap_or(0)
                + item.get("panic").and_then(Value::as_u64).unwrap_or(0)
        };
        score(b).cmp(&score(a))
    });
    let top_findings = findings.iter().take(20).cloned().collect::<Vec<_>>();
    write_json(
        "target/hepta-panic-surface-audit/manifest.json",
        &json!({
            "smoke": "hepta-panic-surface-audit",
            "status": "complete",
            "file_count": files.len(),
            "finding_file_count": findings.len(),
            "totals": totals,
            "top_findings": top_findings,
        }),
    )?;
    println!("Hepta panic surface audit passed");
    Ok(())
}

fn status_for_release_doc(name: &str) -> &'static str {
    if name.contains("HEPTA_CONTROL_UI_100_")
        || name.contains("HEPTA_CONTROL_UI_P0_P6_")
        || name.contains("HEPTA_CONTROL_UI_P0_P13_")
        || name.contains("HEPTA_CONTROL_UI_P0_P21_")
        || name.contains("HEPTA_CONTROL_UI_P0_P29_")
    {
        "superseded by P0-P39 Control UI gates"
    } else if name.contains("P0_P39")
        || name.contains("H40_H49")
        || name.contains("V0_1_INTERNAL_RC")
    {
        "current gate evidence"
    } else {
        "historical release evidence"
    }
}

async fn run_cli_json(cli: &CliApp, command: &str) -> AuditResult<Value> {
    let output = cli.execute_command(command).await?;
    parse_embedded_json(&output, command)
}

fn parse_embedded_json_file(path: impl AsRef<Path>) -> AuditResult<Value> {
    let path = path.as_ref();
    let text = fs::read_to_string(path).map_err(|err| err.to_string())?;
    parse_embedded_json(&text, &path.to_string_lossy())
}

fn parse_embedded_json(text: &str, label: &str) -> AuditResult<Value> {
    let start = text
        .find('{')
        .ok_or_else(|| format!("JSON object not found in {label}"))?;
    let end = text
        .rfind('}')
        .ok_or_else(|| format!("JSON object not found in {label}"))?;
    ensure(end > start, format!("JSON object not found in {label}"))?;
    serde_json::from_str(&text[start..=end])
        .map_err(|err| format!("invalid JSON in {label}: {err}"))
}

fn read_json_file(path: impl AsRef<Path>) -> AuditResult<Value> {
    let path = path.as_ref();
    let text = fs::read_to_string(path).map_err(|err| err.to_string())?;
    serde_json::from_str(&text).map_err(|err| format!("invalid JSON in {}: {err}", path.display()))
}

fn write_json(path: impl AsRef<Path>, value: &Value) -> AuditResult<()> {
    let path = path.as_ref();
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(|err| err.to_string())?;
    }
    let payload = serde_json::to_string_pretty(value).map_err(|err| err.to_string())? + "\n";
    fs::write(path, payload).map_err(|err| err.to_string())
}

fn walk_paths(root: &Path, skip_dirs: &[&str]) -> AuditResult<Vec<PathBuf>> {
    let mut paths = Vec::new();
    if !root.exists() {
        return Ok(paths);
    }
    walk_paths_inner(root, skip_dirs, &mut paths)?;
    paths.sort();
    Ok(paths)
}

fn walk_paths_inner(root: &Path, skip_dirs: &[&str], paths: &mut Vec<PathBuf>) -> AuditResult<()> {
    for entry in fs::read_dir(root).map_err(|err| err.to_string())? {
        let entry = entry.map_err(|err| err.to_string())?;
        let path = entry.path();
        let file_name = entry.file_name().to_string_lossy().to_string();
        let file_type = entry.file_type().map_err(|err| err.to_string())?;
        if file_type.is_dir() {
            if skip_dirs.iter().any(|skip| *skip == file_name) {
                continue;
            }
            walk_paths_inner(&path, skip_dirs, paths)?;
        } else {
            paths.push(path);
        }
    }
    Ok(())
}

fn read_text_file(path: &Path) -> AuditResult<Option<String>> {
    let bytes = fs::read(path).map_err(|err| err.to_string())?;
    if bytes.contains(&0) {
        return Ok(None);
    }
    Ok(String::from_utf8(bytes).ok())
}

fn relative_path(root: &Path, path: &Path) -> AuditResult<PathBuf> {
    path.strip_prefix(root)
        .map(Path::to_path_buf)
        .map_err(|err| err.to_string())
}

fn contains_legacy_branding(text: &str) -> bool {
    text.to_lowercase().contains("openclaw")
}

fn compact(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn clippy_allow_bodies(text: &str) -> Vec<String> {
    let mut bodies = Vec::new();
    let mut search_from = 0usize;
    while let Some(relative_start) = text[search_from..]
        .find("#[allow(")
        .or_else(|| text[search_from..].find("#![allow("))
    {
        let start = search_from + relative_start;
        let Some(open) = text[start..].find('(').map(|offset| start + offset) else {
            break;
        };
        let Some(close_rel) = text[open..].find(")]") else {
            break;
        };
        let close = open + close_rel;
        bodies.push(text[open + 1..close].to_string());
        search_from = close + 2;
    }
    bodies
}

fn count_macro_call(text: &str, macro_name: &str) -> usize {
    let mut count = 0usize;
    let mut rest = text;
    while let Some(index) = rest.find(macro_name) {
        let after = &rest[index + macro_name.len()..];
        if after.trim_start().starts_with('(') {
            count += 1;
        }
        rest = after;
    }
    count
}

fn ensure(condition: bool, message: String) -> AuditResult<()> {
    if condition { Ok(()) } else { Err(message) }
}

fn ensure_json_i64(value: &Value, key: &str, expected: i64, message: &str) -> AuditResult<()> {
    ensure(
        value.get(key).and_then(Value::as_i64) == Some(expected),
        message.to_string(),
    )
}

fn ensure_json_bool(value: &Value, key: &str, expected: bool, message: &str) -> AuditResult<()> {
    ensure(
        value.get(key).and_then(Value::as_bool) == Some(expected),
        message.to_string(),
    )
}

fn ensure_json_min(value: &Value, key: &str, min: i64, message: &str) -> AuditResult<()> {
    ensure(
        value.get(key).and_then(Value::as_i64).unwrap_or_default() >= min,
        message.to_string(),
    )
}
