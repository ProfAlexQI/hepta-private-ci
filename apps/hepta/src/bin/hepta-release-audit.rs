use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

use hepta_cli::CliApp;
use serde_json::{Value, json};

type AuditResult<T> = Result<T, String>;

#[tokio::main]
async fn main() {
    if let Err(err) = run().await {
        eprintln!("hepta-release-audit failed: {err}");
        std::process::exit(1);
    }
}

async fn run() -> AuditResult<()> {
    let target = env::args()
        .nth(1)
        .ok_or_else(|| "usage: hepta-release-audit <target>".to_string())?;
    match target.as_str() {
        "branding-audit" => branding_audit(),
        "docs-release-index" => docs_release_index(),
        "external-adapter-evidence-pack" => external_adapter_evidence_pack(),
        "full-stack-hostile-fuzz" => full_stack_hostile_fuzz().await,
        "intelligence-phase2-smoke" => intelligence_phase2_smoke().await,
        "lint-allowlist-audit" => lint_allowlist_audit(),
        "panic-surface-audit" => panic_surface_audit(),
        other => Err(format!(
            "unknown audit target `{other}`; expected branding-audit, docs-release-index, external-adapter-evidence-pack, full-stack-hostile-fuzz, intelligence-phase2-smoke, lint-allowlist-audit, panic-surface-audit"
        )),
    }
}

fn branding_audit() -> AuditResult<()> {
    let root = env::current_dir().map_err(|err| err.to_string())?;
    let mut text_violations = Vec::new();
    let mut path_violations = Vec::new();
    let mut vendor_matches = 0usize;
    let skip_dirs = [
        ".git",
        "target",
        "node_modules",
        ".hepta",
        "dist",
        "artifacts",
        "tmp",
    ];

    for path in walk_paths(&root, &skip_dirs)? {
        let relative = relative_path(&root, &path)?;
        let components = relative
            .components()
            .map(|component| component.as_os_str().to_string_lossy().to_string())
            .collect::<Vec<_>>();
        let in_vendor = components.iter().any(|component| component == "vendor");
        let relative_display = relative.to_string_lossy().to_string();
        if contains_legacy_branding(&relative_display) {
            if in_vendor {
                vendor_matches += 1;
            } else {
                path_violations.push(relative_display.clone());
            }
        }
        if in_vendor || !path.is_file() {
            continue;
        }
        let Some(text) = read_text_file(&path)? else {
            continue;
        };
        for (index, line) in text.lines().enumerate() {
            if contains_legacy_branding(line) {
                text_violations.push(format!(
                    "{}:{}:{}",
                    relative_display,
                    index + 1,
                    line.trim().chars().take(180).collect::<String>()
                ));
            }
        }
    }

    ensure(
        path_violations.is_empty(),
        format!(
            "Hepta-owned paths still contain legacy branding:\n{}",
            path_violations
                .iter()
                .take(80)
                .cloned()
                .collect::<Vec<_>>()
                .join("\n")
        ),
    )?;
    ensure(
        text_violations.is_empty(),
        format!(
            "Hepta-owned text still contains legacy branding:\n{}",
            text_violations
                .iter()
                .take(80)
                .cloned()
                .collect::<Vec<_>>()
                .join("\n")
        ),
    )?;
    println!(
        "Hepta branding audit passed (vendor compatibility matches ignored: {vendor_matches})"
    );
    Ok(())
}

fn docs_release_index() -> AuditResult<()> {
    let release_dir = Path::new("docs/release");
    let mut docs = fs::read_dir(release_dir)
        .map_err(|err| err.to_string())?
        .filter_map(Result::ok)
        .map(|entry| entry.file_name().to_string_lossy().to_string())
        .filter(|name| name.ends_with(".md") && name != "INDEX.md")
        .collect::<Vec<_>>();
    docs.sort();
    ensure(
        docs.len() >= 20,
        "release index expects a non-trivial release doc corpus".to_string(),
    )?;

    let superseded_count = docs
        .iter()
        .filter(|name| status_for_release_doc(name).starts_with("superseded"))
        .count();
    let mut lines = vec![
        "# Hepta Release Documentation Index".to_string(),
        String::new(),
        "Generated by `cargo run -q -p hepta --bin hepta-release-audit -- docs-release-index`.".to_string(),
        String::new(),
        "This index keeps the growing release corpus searchable and marks obviously superseded Control UI milestones without deleting historical evidence.".to_string(),
        String::new(),
        "| Document | Status |".to_string(),
        "| --- | --- |".to_string(),
    ];
    lines.extend(
        docs.iter()
            .map(|name| format!("| [{name}](./{name}) | {} |", status_for_release_doc(name))),
    );
    lines.push(String::new());
    fs::write(release_dir.join("INDEX.md"), lines.join("\n")).map_err(|err| err.to_string())?;

    write_json(
        "target/hepta-docs-release-index/manifest.json",
        &json!({
            "smoke": "hepta-docs-release-index",
            "status": "complete",
            "document_count": docs.len(),
            "superseded_count": superseded_count,
        }),
    )?;
    println!("Hepta docs release index generated");
    Ok(())
}

fn external_adapter_evidence_pack() -> AuditResult<()> {
    let external_manifest_path = Path::new(".hepta/external-production/manifest.json");
    ensure(
        external_manifest_path.exists(),
        "external production evidence manifest missing".to_string(),
    )?;
    let external_manifest = read_json_file(external_manifest_path)?;
    let evidence = external_manifest
        .get("evidence")
        .and_then(Value::as_object)
        .cloned()
        .unwrap_or_default();
    let verified_count = evidence
        .values()
        .filter(|item| item.get("verified").and_then(Value::as_bool) == Some(true))
        .count();
    let credentialed_signals = [
        "credentialed-provider-smoke",
        "channel-delivery-smoke",
        "remote-branch-ci-smoke",
    ]
    .into_iter()
    .filter(|id| {
        evidence
            .get(*id)
            .and_then(|item| item.get("verified"))
            .and_then(Value::as_bool)
            == Some(true)
    })
    .collect::<Vec<_>>();
    let manual_attestation_ready =
        Path::new("docs/quality/HEPTA_EXTERNAL_ADAPTER_EVIDENCE_PACK_2026-04-28.md").exists();
    let evidence_classes = json!([
        { "id": "local-mirror", "ready": verified_count >= 6, "note": "deterministic local contract and fixture evidence" },
        { "id": "credentialed-smoke", "ready": !credentialed_signals.is_empty(), "note": "redacted evidence refs for previously approved external smoke" },
        { "id": "manual-attestation", "ready": manual_attestation_ready, "note": "operator-readable evidence classification exists" },
    ]);
    ensure(
        verified_count >= 6,
        "local mirror external readiness must be complete".to_string(),
    )?;
    ensure(
        manual_attestation_ready,
        "manual attestation ledger must exist".to_string(),
    )?;
    write_json(
        "target/hepta-external-adapter-evidence-pack/manifest.json",
        &json!({
            "smoke": "hepta-external-adapter-evidence-pack",
            "status": "complete",
            "external_production_ready": verified_count >= 17,
            "verified_external_evidence_count": verified_count,
            "production_surface_status": "complete",
            "credentialed_smoke_ready": !credentialed_signals.is_empty(),
            "credentialed_smoke_decision_required": credentialed_signals.is_empty(),
            "credential_signal_count": credentialed_signals.len(),
            "credentialed_signal_ids": credentialed_signals,
            "evidence_classes": evidence_classes,
        }),
    )?;
    println!("Hepta external adapter evidence pack passed");
    Ok(())
}

async fn full_stack_hostile_fuzz() -> AuditResult<()> {
    let cli = CliApp::new();
    let payloads = vec![
        "<script>window.__HEPTA_XSS=1</script>".to_string(),
        "../../../../tmp/hepta-path-traversal".to_string(),
        "$(touch /tmp/hepta-command-injection)".to_string(),
        "javascript:alert(1)".to_string(),
        "{\"malformed\": [1,2,}".to_string(),
        "x".repeat(4096),
    ];
    let mut results = Vec::new();
    for payload in &payloads {
        let transcript = run_cli_json(&cli, &format!("/query-transcript {payload} --json")).await?;
        ensure(
            transcript.get("status").and_then(Value::as_str) == Some("complete")
                || transcript.get("query").is_some(),
            "query transcript should stay structured".to_string(),
        )?;
        let recall = run_cli_json(&cli, &format!("/recall {payload} --json")).await?;
        ensure(
            recall.get("status").and_then(Value::as_str) == Some("complete")
                || recall.get("query").is_some()
                || recall.get("report").is_some()
                || recall.get("request").is_some(),
            "recall should stay structured".to_string(),
        )?;
        let task = run_cli_json(&cli, &format!("/spawn-task fuzz-worker {payload} --json")).await?;
        ensure(
            task.get("task").is_some()
                || task.get("task_id").is_some()
                || task.get("status").and_then(Value::as_str) == Some("complete"),
            "spawn-task hostile payload should stay structured and local".to_string(),
        )?;
        results.push(json!({
            "payload_bytes": payload.len(),
            "transcript_ok": true,
            "recall_ok": true,
            "spawn_task_ok": true,
        }));
    }
    let control_ui = run_cli_json(&cli, "/control-ui --json").await?;
    ensure(
        control_ui.get("status").and_then(Value::as_str) == Some("complete")
            || control_ui.get("control_ui_percent").is_some(),
        "control-ui hostile fixture replacement should stay structured".to_string(),
    )?;
    write_json(
        "target/hepta-full-stack-hostile-fuzz/manifest.json",
        &json!({
            "smoke": "hepta-full-stack-hostile-fuzz",
            "status": "complete",
            "payload_count": payloads.len(),
            "boundaries": ["cli", "query", "recall", "worker-task", "control-ui"],
            "results": results,
        }),
    )?;
    println!("Hepta full-stack hostile fuzz gate passed");
    Ok(())
}

