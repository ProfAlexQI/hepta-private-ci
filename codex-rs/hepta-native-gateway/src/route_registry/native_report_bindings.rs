pub(crate) fn native_report_id(path: &str) -> Option<NativeReportId> {
    if let Some(route_index) = CONTROL_UI_ROUTE_SPECS
        .iter()
        .position(|route| route.method == "GET" && route.pattern == path)
        .and_then(|index| u16::try_from(index).ok())
        && let Some(binding) = CONTROL_UI_NATIVE_REPORT_BINDINGS
            .iter()
            .find(|binding| binding.route_index == route_index)
    {
        return Some(binding.report_id);
    }
    SPECIAL_NATIVE_REPORT_ROUTES
        .iter()
        .find_map(|route| (route.path == path).then_some(route.report_id))
}

#[cfg(test)]
pub(crate) fn registered_native_report_paths() -> impl Iterator<Item = &'static str> {
    CONTROL_UI_NATIVE_REPORT_BINDINGS
        .iter()
        .map(|binding| CONTROL_UI_ROUTE_SPECS[usize::from(binding.route_index)].pattern)
        .chain(SPECIAL_NATIVE_REPORT_ROUTES.iter().map(|route| route.path))
}
